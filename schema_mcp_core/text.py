def concepts(raw_terms) -> list[set[str]]:
    """Слова запроса → понятия. Одно понятие это корень плюс его английские
    соответствия.

    Группировка нужна для честного счёта покрытия: «статистика» и «statistic»
    это одно слово пользователя, а не два. Пока они считались раздельно, метод,
    совпавший с тремя синонимами одного понятия, обгонял метод, совпавший с
    двумя разными понятиями запроса.
    """
    out: list[set[str]] = []
    seen: set[str] = set()
    for raw in raw_terms:
        base = stem(raw)
        if base in seen:
            continue
        seen.add(base)
        group = {base} | set(TRANSLATIONS.get(base, ()))
        out.append(group)
    return out


def wants_write(raw_terms) -> bool:
    """Намерение считается по исходным словам запроса, до стемминга."""
    return any(t.lower() in WRITE_INTENT for t in raw_terms)
