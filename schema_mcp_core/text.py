TRANSLATIONS: dict[str, tuple[str, ...]] = {}
for _word, _targets in _TRANSLATION_WORDS.items():
    _key = stem(_word)
    TRANSLATIONS[_key] = TRANSLATIONS.get(_key, ()) + tuple(stem(x) for x in _targets)


# Слова, после которых читающий метод пользователю не нужен: он просит
# действие. Сверка идёт по ЦЕЛОМУ слову, а не по основе: у «подпись» и
# «подписать» основа общая, и по ней запрос «документы на подпись» выглядел бы
# просьбой что-то подписать. Поэтому здесь перечислены живые формы глагола.
