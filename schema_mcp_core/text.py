"""Лёгкая нормализация слов для поиска по каталогу.

Зачем свой стеммер, а не pymorphy: сервер ставится через `uvx` одной строкой,
и тянуть словарь на десятки мегабайт ради ранжирования пятидесяти методов
дорого. Здесь отсечение окончаний, которого хватает, чтобы «вакансии»,
«вакансий» и «вакансия» сошлись в один ключ.

Правило одно: стем не короче MIN_STEM символов, иначе короткие корни вроде
«код» и «акт» срежутся до огрызка и поиск начнёт врать.
"""
from __future__ import annotations

import re

MIN_STEM = 3

# Порядок важен: длинные окончания проверяются первыми, иначе «ами» никогда не
# сработает, потому что «и» отрежется раньше.
_RU_ENDINGS = (
    "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими", "ость",
    "ться", "тся", "ешь", "ишь", "ует", "уют", "ают", "ять", "ить", "ать",
    "еть", "ыть", "ей", "ой", "ый", "ий", "ая", "яя", "ое", "ее", "ые", "ие",
    "ов", "ев", "ам", "ям", "ах", "ях", "ом", "ем", "ла", "ло", "ли", "ил",
    "а", "я", "е", "о", "у", "ю", "ы", "и", "ь", "й",
)

_EN_ENDINGS = ("ing", "es", "ed", "s")

# Подчёркивание это \w, поэтому явный класс: иначе operation_id вида
# hh_search_for_vacancy остаётся одним неделимым словом.
_WORD = re.compile(r"[^0-9A-Za-zА-Яа-яЁё]+")


def stem(token: str) -> str:
    """Слово → грубая основа. Короткие слова возвращаются как есть."""
    t = token.lower().replace("ё", "е")
    endings = _RU_ENDINGS if re.search(r"[а-я]", t) else _EN_ENDINGS
    # vacancies → vacancy, а не vacanc: иначе множественное число в запросе не
    # встречается с единственным в operation_id.
    if endings is _EN_ENDINGS and t.endswith("ies") and len(t) - 3 >= MIN_STEM:
        t = t[:-3] + "y"
    for end in endings:
        if len(t) > MIN_STEM and t.endswith(end) and len(t) - len(end) >= MIN_STEM:
            t = t[: -len(end)]
            break
    # Второй проход снимает ТОЛЬКО одну гласную: «вакансии» после первого
    # прохода это «ваканси», а «вакансий» уже «ваканс», и без добора падежи не
    # сходятся. Снимать второе многобуквенное окончание нельзя: «рекламы»
    # превращалось в «рекл», и словарь переводов переставал срабатывать.
    if endings is _RU_ENDINGS and len(t) > MIN_STEM and t[-1] in "аеиоуыэюяьй":
        t = t[:-1]
    return t


def tokens(text: str) -> list[str]:
    """Текст → слова. Змеиный и верблюжий регистр разбираются на части:
    `hh_get_vacancy_areas` это четыре слова, а не одно."""
    spaced = re.sub(r"(?<=[a-zа-я])(?=[A-ZА-Я])", " ", text)
    return [t for t in _WORD.split(spaced.lower()) if t]


def stems(text: str) -> set[str]:
    return {stem(t) for t in tokens(text)}


